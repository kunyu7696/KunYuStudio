/** 工具类名与构造器攻击力参数类型（Mojmap：Sword/Pickaxe/Hoe 传 int，Axe/Shovel 传 float） */
const MOJMAP_TOOL_CLASSES: Record<ToolKind, { cls: string; intDamage: boolean }> = {
  pickaxe: { cls: 'PickaxeItem', intDamage: true },
  axe: { cls: 'AxeItem', intDamage: false },
  shovel: { cls: 'ShovelItem', intDamage: false },
  hoe: { cls: 'HoeItem', intDamage: true },
  sword: { cls: 'SwordItem', intDamage: true }
}

/** Mojmap <1.20 盔甲构造器/耐久方法接收 EquipmentSlot（与 Yarn 侧同一对照），slot → 枚举成员 */
const MOJMAP_ARMOR_EQUIPMENT_SLOTS: Record<ArmorSlot, string> = {
  helmet: 'HEAD',
  chestplate: 'CHEST',
  leggings: 'LEGS',
  boots: 'FEET'
}

function mojmapItemField(i: ItemSchema, f: MojmapFlavor): string {
  const name = itemDisplayName(i, 'zh_cn')
  let comment = `/** ${name} */`
  if (i.itemType === 'block_item' && i.blockRef) {
    comment = `/** ${name}（方块物品，引用 ${i.blockRef}；方块本体注册见 ModBlocks） */`
  } else if (i.description) {
    comment = `/** ${name}：${oneLine(i.description)} */`
  }

  let ctor = 'Item'
  let argsPrefix = ''
  let maxDamageExpr: string | null | undefined
  const settings: string[] = []

  if (i.itemType === 'tool' && i.tool) {
    const t = i.tool
    const meta = MOJMAP_TOOL_CLASSES[t.toolKind]
    ctor = meta.cls
    // 1.21.2~1.21.4：Tiers 枚举删除，改用 ToolMaterial record（javap 实证）
    const material = `${f.toolMaterialEra ? 'ToolMaterial' : 'Tiers'}.${t.material.toUpperCase()}`
    const dmg = meta.intDamage ? `${Math.trunc(t.attackDamage)}` : fmtFloat(t.attackDamage)
    if (f.dataComponentItems) {
      // 1.21.5+：裸 Item + Properties.pickaxe()/sword() 等（签名统一 (ToolMaterial, float, float)，
      // 内建 ToolComponent/WeaponComponent、攻击属性与材质耐久，无需 durability 兜底）
      ctor = 'Item'
      const dcMaterial = `ToolMaterial.${t.material.toUpperCase()}`
      settings.push(
        `            .${t.toolKind}(${dcMaterial}, ${fmtFloat(t.attackDamage)}, ${fmtFloat(t.attackSpeed)})`
      )
      maxDamageExpr = null
    } else if (f.toolMaterialEra) {
      // 1.21.2~1.21.4：构造器 (ToolMaterial, float dmg, float speed, Properties)，耐久走 record 访问器
      argsPrefix = `${material}, ${fmtFloat(t.attackDamage)}, ${fmtFloat(t.attackSpeed)}, `
      maxDamageExpr = `${material}.durability()`
    } else if (f.toolViaAttributes) {
      // 1.20.5+：构造器收窄为 (Tier, Properties)，攻击力/攻速走 attributeModifiers（Data Components）
      argsPrefix = `${material}, `
      settings.push('            .attributes(ItemAttributeModifiers.builder()')
      settings.push(
        `                .add(Attributes.ATTACK_DAMAGE, new AttributeModifier(${f.attributeModifierId('attack_damage')}, ${dmg}, AttributeModifier.Operation.ADD_VALUE), EquipmentSlotGroup.MAINHAND)`
      )
      settings.push(
        `                .add(Attributes.ATTACK_SPEED, new AttributeModifier(${f.attributeModifierId('attack_speed')}, ${fmtFloat(t.attackSpeed)}, AttributeModifier.Operation.ADD_VALUE), EquipmentSlotGroup.MAINHAND)`
      )
      settings.push('                .build())')
    } else {
      argsPrefix = `${material}, ${dmg}, ${fmtFloat(t.attackSpeed)}, `
    }
    // 工具/盔甲没有耐久条不符合原版行为（Tier 耐久需显式应用）
    if (!f.dataComponentItems && !f.toolMaterialEra) maxDamageExpr = `${material}.getUses()`
  } else if (i.itemType === 'armor' && i.armor) {
    const a = i.armor
    ctor = 'ArmorItem'
    // 1.21.2 起 ArmorMaterials 常量恢复 CHAINMAIL（equipment 包 record 时代），
    // CHAIN 别名仅存在于 1.20.5~1.21.1 的 Holder 过渡期
    const materialConst = armorMaterialConstant(
      a.material,
      f.toolViaAttributes && !f.toolMaterialEra
    )
    if (f.dataComponentItems) {
      // 1.21.5+：裸 Item + Properties.humanoidArmor(ArmorMaterial, ArmorType)，
      // 内建 EquippableComponent、防御/韧性属性与 maxDamage（材质耐久 × 槽位倍数）。
      // 注意 Mojmap 1.21.5+ ArmorMaterials 常量恢复 CHAINMAIL（与 1.20.5~1.21.1 的 CHAIN 不同）
      ctor = 'Item'
      const dcConst = a.material.toUpperCase()
      settings.push(
        `            .humanoidArmor(ArmorMaterials.${dcConst}, ArmorType.${a.slot.toUpperCase()})`
      )
      maxDamageExpr = null
    } else if (f.toolMaterialEra) {
      // 1.21.2~1.21.4：ArmorItem(ArmorMaterial, ArmorType, Properties)（equipment 包，javap 实证）；
      // 耐久 = ArmorType.getDurability(材质基础耐久)
      const slotArg = `ArmorType.${a.slot.toUpperCase()}`
      argsPrefix = `ArmorMaterials.${materialConst}, ${slotArg}, `
      maxDamageExpr = `${slotArg}.getDurability(ArmorMaterials.${materialConst}.durability())`
    } else if (f.armorViaEquipmentSlot) {
      // 1.20-：ArmorItem.Type 尚不存在（门禁实证 1.19.2），构造器与耐久方法均接收 EquipmentSlot
      const slotArg = `EquipmentSlot.${MOJMAP_ARMOR_EQUIPMENT_SLOTS[a.slot]}`
      argsPrefix = `ArmorMaterials.${materialConst}, ${slotArg}, `
      maxDamageExpr = `ArmorMaterials.${materialConst}.getDurabilityForSlot(${slotArg})`
    } else {
      const slot = `ArmorItem.Type.${a.slot.toUpperCase()}`
      argsPrefix = `ArmorMaterials.${materialConst}, ${slot}, `
      maxDamageExpr = f.toolViaAttributes
        ? // 1.20.5+：原版 ArmorMaterial 经 Holder 间接引用，改用 Type.getDurability(multiplier) 数值表
          `${slot}.getDurability(${ARMOR_DURABILITY_MULTIPLIER[a.material]})`
        : // 1.20.x：ArmorMaterials 枚举自带 getDurabilityForType(Type)（Mojmap 实证方法名）
          `ArmorMaterials.${materialConst}.getDurabilityForType(${slot})`
    }
  }

  if (i.properties.maxDamage > 0) {
    // 显式耐久放链尾，后写覆盖保证语义正确
    settings.push(`            .durability(${Math.floor(i.properties.maxDamage)})`)
  } else if (maxDamageExpr === null) {
    // 耐久已由 Settings/Properties 辅助方法内建（1.21.5+），无需兜底也不退化为堆叠
  } else if (maxDamageExpr) {
    settings.push(`            .durability(${maxDamageExpr})`)
  } else {
    settings.push(`            .stacksTo(${clampStack(i.properties.maxCount)})`)
  }
  if (i.properties.rarity !== 'common') {
    settings.push(`            .rarity(Rarity.${i.properties.rarity.toUpperCase()})`)
  }
  if (i.properties.fireproof) settings.push('            .fireproof()')

  if (i.itemType === 'food' && i.food) {
    const fd = i.food
    const foodLines = [
      `            .food(new FoodProperties.Builder()`,
      `                .nutrition(${Math.floor(fd.hunger)})`,
      `                .${f.foodSaturation}(${fmtFloat(fd.saturation)})`
    ]
    if (fd.meat) foodLines.push('                .meat()')
    if (fd.alwaysEdible) foodLines.push('                .alwaysEdible()')
    for (const e of fd.effects) {
      const constant = foodEffectConstant(e.effect, 'mojmap')
      if (!constant) {
        foodLines.push(`                // TODO 效果 ${e.effect} 不在常用效果清单，已跳过`)
        continue
      }
      foodLines.push(
        `                .effect(new MobEffectInstance(MobEffects.${constant}, ${Math.floor(e.duration)}, ${Math.floor(e.amplifier)}), ${fmtFloat(e.chance)})`
      )
    }
    foodLines.push('                .build()')
    foodLines.push('            )')
    settings.push(...foodLines)
  }

  const chain =
    settings.length > 0 ? `new Item.Properties()\n${settings.join('\n')}` : 'new Item.Properties()'
  // 1.18 及以前原版工具类构造器为 protected（javap 实证），外部包需用匿名子类实例化
  const ctorTail =
    i.itemType === 'tool' && !f.toolViaAttributes && f.toolCtorNeedsAnon ? ' {}' : ''
  return `    ${comment}
    public static final ${f.itemHolder}<${ctor}> ${toJavaConst(i.id)} = ITEMS.register("${i.id}",
        () -> new ${ctor}(${argsPrefix}${chain})${ctorTail});`
}

export function mojmapModItemsJava(
  ctx: ModContext,
  blocks: GeneratorBlock[],
  items: ItemSchema[],
  entities: EntitySchema[] = []
): string {
  const f = resolveMojmapFlavor(ctx.loader === 'neoforge' ? 'neoforge' : 'forge', ctx.mcVersion)
  // 仅为已注册（已建模）且启用刷怪蛋的实体生成刷怪蛋物品（实体本体注册见 ModEntities）
  const eggEntities = entities.filter((e) => e.spawnEgg.enabled)
  const needRarity = items.some((i) => i.properties.rarity !== 'common')
  const needFood = items.some((i) => i.itemType === 'food')
  const needFoodEffect = items.some(
    (i) => i.itemType === 'food' && (i.food?.effects.length ?? 0) > 0
  )
  const toolItems = items.filter((i) => i.itemType === 'tool' && i.tool)
  const armorItems = items.filter((i) => i.itemType === 'armor')
  const usedToolClasses = [
    ...new Set(toolItems.map((i) => MOJMAP_TOOL_CLASSES[i.tool!.toolKind].cls))
  ]

  const blockItemFields = blocks.map((b) => {
    const name = oneLine(b.displayName)
    return `    /** ${name}（方块物品） */
    public static final ${f.itemHolder}<Item> ${toJavaConst(b.id)} = ITEMS.register("${b.id}",
        () -> new BlockItem(ModBlocks.${toJavaConst(b.id)}.get(), new Item.Properties()));`
  })

  const itemFields = items.map((i) => mojmapItemField(i, f))
  // 刷怪蛋字段：颜色为 0xRRGGBB 十进制字面量（对齐 fabric 分支的 parseInt 转换）；
  // ModEntities 与 ModItems 同在 registry 包，无需 import
  const eggFields = eggEntities.map((e) => {
    const primary = parseInt((e.properties.primaryColor ?? '#000000').replace('#', ''), 16)
    const secondary = parseInt((e.properties.secondaryColor ?? '#000000').replace('#', ''), 16)
    const name = oneLine(e.displayName.zh_cn || e.id)
    if (f.spawnEggVanilla) {
      // 1.21.5+（NeoForge）：DeferredSpawnEggItem 移除，原版 SpawnEggItem(EntityType, Properties)，颜色数据驱动化
      return `    /** ${name}刷怪蛋 */
    public static final ${f.itemHolder}<Item> ${toJavaConst(e.id)}_SPAWN_EGG = ITEMS.register("${e.id}_spawn_egg",
        () -> new SpawnEggItem(ModEntities.${toJavaConst(e.id)}.get(), new Item.Properties()));`
    }
    return `    /** ${name}刷怪蛋 */
    public static final ${f.itemHolder}<Item> ${toJavaConst(e.id)}_SPAWN_EGG = ITEMS.register("${e.id}_spawn_egg",
        () -> new ${f.spawnEggClass}(ModEntities.${toJavaConst(e.id)}, ${primary}, ${secondary}, new Item.Properties()));`
  })
  const fields = [...blockItemFields, ...itemFields, ...eggFields].join('\n\n')
  const total = blocks.length + items.length + eggEntities.length
  const needItemImport = total > 0

  // 1.21.5+ 原版工具/盔甲子类已删除（数据组件化），相关 import 必须跳过
  const toolImports = f.dataComponentItems
    ? ''
    : usedToolClasses.map((c) => `import net.minecraft.world.item.${c};\n`).join('')
  const imports = `import ${ctx.packageName}.${ctx.modClassName};
${total > 0 ? f.registriesImport.map((i) => `import ${i};`).join('\n') + '\n' : ''}${
    needItemImport ? `import ${f.itemHolderImport};\n` : ''
  }${blocks.length > 0 ? 'import net.minecraft.world.item.BlockItem;\n' : ''}${
    needItemImport ? 'import net.minecraft.world.item.Item;\n' : ''
  }${needRarity ? 'import net.minecraft.world.item.Rarity;\n' : ''}${needFood ? 'import net.minecraft.world.food.FoodProperties;\n' : ''}${
    needFoodEffect
      ? `import net.minecraft.world.effect.MobEffectInstance;
import net.minecraft.world.effect.MobEffects;
`
      : ''
  }${toolItems.length > 0 ? `${
    // 1.21.2 起 Tiers 枚举删除、ToolMaterial record 上位（两个时代 import 同路径）
    f.dataComponentItems || f.toolMaterialEra
      ? 'import net.minecraft.world.item.ToolMaterial;\n'
      : `import net.minecraft.world.item.Tiers;\n`
  }${f.dataComponentItems ? '' : toolImports}${
    f.toolViaAttributes && !f.dataComponentItems && !f.toolMaterialEra
      ? `import net.minecraft.world.entity.EquipmentSlotGroup;
import net.minecraft.world.entity.ai.attributes.AttributeModifier;
import net.minecraft.world.entity.ai.attributes.Attributes;
import net.minecraft.world.item.component.ItemAttributeModifiers;
${f.attributeModifierIdImport ? `import ${f.attributeModifierIdImport};\n` : ''}`
      : ''
  }` : ''}${
    armorItems.length > 0
      ? f.dataComponentItems
        ? `import net.minecraft.world.item.equipment.ArmorMaterials;
import net.minecraft.world.item.equipment.ArmorType;
`
        : f.toolMaterialEra
          ? // 1.21.2~1.21.4：ArmorItem 子类仍在，但 ArmorMaterials/ArmorType 已迁 equipment 包
            `import net.minecraft.world.item.ArmorItem;
import net.minecraft.world.item.equipment.ArmorMaterials;
import net.minecraft.world.item.equipment.ArmorType;
`
          : `import net.minecraft.world.item.ArmorItem;
import net.minecraft.world.item.ArmorMaterials;
${f.armorViaEquipmentSlot ? 'import net.minecraft.world.entity.EquipmentSlot;\n' : ''}`
      : ''
  }${eggEntities.length > 0 ? `import ${f.spawnEggVanilla ? 'net.minecraft.world.item.SpawnEggItem' : f.spawnEggImport};\n` : ''}`

  return `package ${ctx.packageName}.registry;

${imports}
/**
 * ${GENERATED_BANNER}
 */
public class ModItems {
    ${f.itemsRegistryDecl(ctx.modClassName)}

${fields || '    // 暂无由可视化编辑器管理的物品'}
}
`
}
