export function mojmapModBlocksJava(ctx: ModContext, blocks: GeneratorBlock[]): string {
  const f = resolveMojmapFlavor(ctx.loader === 'neoforge' ? 'neoforge' : 'forge', ctx.mcVersion)
  const needNonOpaque = blocks.some((b) => b.preset === 'glass' || b.collisionType !== 'full')
  const needNoCollision = blocks.some((b) => b.collisionType === 'none')

  // 1.20- 无 no-arg Properties.of()，需 of(Material.STONE)（门禁实证 1.19.2 失败 / 1.20.1 通过）
  const propsExpr = f.blockPropsNeedsMaterial
    ? 'BlockBehaviour.Properties.of(Material.STONE)'
    : 'BlockBehaviour.Properties.of()'
  const fields = blocks
    .map((b) => {
      const chain: string[] = []
      chain.push(`            .strength(${fmtFloat(b.hardness)}, ${fmtFloat(b.resistance)})`)
      chain.push(`            .sound(SoundType.${b.soundGroup.toUpperCase()})`)
      if (b.requiresTool) chain.push('            .requiresCorrectToolForDrops()')
      if (b.luminance > 0) chain.push(`            .lightLevel(state -> ${b.luminance})`)
      if (needNoCollision && b.collisionType === 'none') chain.push('            .noCollision()')
      else if (needNonOpaque && (b.preset === 'glass' || b.collisionType !== 'full')) {
        chain.push('            .noOcclusion()')
      }
      const comment = b.description ? `/** ${b.displayName}：${oneLine(b.description)} */` : `/** ${b.displayName} */`
      return `    ${comment}
    public static final ${f.holder} ${toJavaConst(b.id)} = BLOCKS.register("${b.id}",
        () -> new Block(${propsExpr}
${chain.join('\n')}));`
    })
    .join('\n\n')

  // Block import 必须无条件：类体中 DeferredRegister<Block> 字段即使零方块也引用 Block
  const materialImport = f.blockPropsNeedsMaterial
    ? 'import net.minecraft.world.level.material.Material;\n'
    : ''
  const imports = blocks.length
    ? `import ${ctx.packageName}.${ctx.modClassName};
${f.registriesImport.map((i) => `import ${i};`).join('\n')}
import ${f.holderImport};
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.state.BlockBehaviour;
${materialImport}`
    : `import ${ctx.packageName}.${ctx.modClassName};
${f.registriesImport.map((i) => `import ${i};`).join('\n')}
import net.minecraft.world.level.block.Block;
`

  return `package ${ctx.packageName}.registry;

${imports}
/**
 * ${GENERATED_BANNER}
 */
public class ModBlocks {
    public static final DeferredRegister<Block> BLOCKS =
        DeferredRegister.create(${f.blockRegistryRef}, ${ctx.modClassName}.MOD_ID);

${fields || '    // 暂无由可视化编辑器管理的方块'}
}
`
}

