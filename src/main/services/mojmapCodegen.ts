/**
 * 盔甲耐久 multiplier 表（Mojmap 1.20.5+：ArmorItem.Type.getDurability(multiplier)；
 * Yarn 1.20.5+：ArmorItem.Type.getMaxDamage(multiplier)——同一数值表跨映射复用）。
 * 语义层材质限定原版 6 种，数值与原版 ArmorMaterial 定义一致且跨版本稳定，
 * 用常数表规避 ArmorMaterial 方法名跨版本漂移。
 */
export const ARMOR_DURABILITY_MULTIPLIER: Record<ArmorMaterial, number> = {
  leather: 5,
  chainmail: 15,
  iron: 15,
  gold: 7,
  diamond: 33,
  netherite: 37
}

/**
 * ArmorMaterials 常量名按版本取值：1.20.5 起原版成员 CHAINMAIL 改名 CHAIN
 * （Yarn/Mojmap 同轮，其余五种材质常量名跨版本稳定）。
 */
export function armorMaterialConstant(material: ArmorMaterial, componentRefactor: boolean): string {
  return componentRefactor && material === 'chainmail' ? 'CHAIN' : material.toUpperCase()
}

const GENERATED_BANNER =
  'AUTO-GENERATED by KunYu Studio — 请勿手动编辑。\n * 由可视化编辑器根据 .kunyu/content 语义资产生成，修改请在可视化编辑器中进行。'

export interface MojmapFlavor {
  loader: 'forge' | 'neoforge'
  /** 方块注册项字段的完整 Java 类型：RegistryObject<Block>（Forge）/ DeferredHolder<Block, Block>（NeoForge 双泛型） */
  holder: string
  holderImport: string
  /** 物品注册项持有类型：RegistryObject（Forge）/ DeferredItem（NeoForge 单泛型） */
  itemHolder: string
  itemHolderImport: string
  /** 1.20.5+ 物品组件重构：工具走 (Tier, Properties)+attributeModifiers；≤1.20.4 走 (Tier, dmg, speed, Properties) */
  toolViaAttributes: boolean
  /** 工具类构造器为 protected（1.18 及更早，javap 实证）：需以匿名子类实例化 */
  toolCtorNeedsAnon: boolean
  /** 1.20- 方块属性无 no-arg of() 工厂（门禁实证：1.19.2 失败、1.20.1 通过），需 of(Material.STONE) */
  blockPropsNeedsMaterial: boolean
  /** 1.20- 盔甲构造器/耐久方法接收 EquipmentSlot（ArmorItem.Type 1.20 起才存在，门禁实证同上） */
  armorViaEquipmentSlot: boolean
  /** 1.21.5+ 数据组件化（NFRT 映射 jar javap 实证）：原版删除 PickaxeItem/ArmorItem 子类，
   * 工具走 Item.Properties.pickaxe()/sword() 等辅助方法（ToolMaterial 单数 record），
   * 盔甲走 humanoidArmor(ArmorMaterial, ArmorType)（注意 Mojmap 槽位枚举为 ArmorType、
   * 材质常量恢复 CHAINMAIL，均与 Yarn 侧 armor()/EquipmentType/CHAIN 不同） */
  dataComponentItems: boolean
  /** 1.21.2~1.21.4 过渡时代（1.21.3 NFRT 映射 jar javap 实证）：Tiers 枚举删除、
   * ToolMaterial record 上位（durability() 访问器），PickaxeItem 等子类构造器改
   * (ToolMaterial, float dmg, float speed, Properties)；ArmorMaterials 迁入
   * net.minecraft.world.item.equipment（常量恢复 CHAINMAIL），ArmorItem 构造器改
   * (ArmorMaterial, ArmorType, Properties)，耐久 = ArmorType.getDurability(material.durability()) */
  toolMaterialEra: boolean
  /** 1.21.5+ NeoForge 移除 DeferredSpawnEggItem，刷怪蛋回归原版 SpawnEggItem(EntityType, Properties) */
  spawnEggVanilla: boolean
  /** 属性修饰符 ID 表达式（1.20.5/6 为 String 字面量；1.21 起改用 ResourceLocation） */
  attributeModifierId: (name: string) => string
  /** 属性修饰符 ID 所需 import（1.21+ 为 ResourceLocation；否则 null） */
  attributeModifierIdImport: string | null
  registriesImport: string[]
  /** 方块/物品注册源的 import 与工厂片段 */
  blockRegistryRef: string
  /** ModItems 的 ITEMS 注册表声明（多行，含缩进） */
  itemsRegistryDecl: (modClassName: string) => string
  /** Item.Properties.food 链中饱和度方法名（1.20.1 saturationMod / 1.21.1 saturationModifier） */
  foodSaturation: string
  /** 实体注册源（DeferredRegister.create 用）：ForgeRegistries.ENTITY_TYPES / Registries.ENTITY_TYPE */
  entityRegistryRef: string
  /** 实体注册项持有类型（按实体类名参数化）：RegistryObject<EntityType<X>> / DeferredHolder<EntityType<?>, EntityType<X>> */
  entityHolder: (entityClass: string) => string
  /** 实体持有类型 import */
  entityHolderImport: string
  /** 刷怪蛋物品类名与 import（构造器签名两加载器一致：supplier, primary, secondary, Properties） */
  spawnEggClass: string
  spawnEggImport: string
  /** MOD 事件总线订阅类/事件的 import 组（实体属性/渲染注册 Setup 类用） */
  eventImports: {
    /** Forge：net.minecraftforge.fml.common.Mod（@Mod.EventBusSubscriber）；NeoForge：net.neoforged.fml.common.EventBusSubscriber（独立注解） */
    busSubscriber: string
    subscribeEvent: string
    dist: string
    attributeCreation: string
    entityRenderers: string
  }
  /** MOD 总线订阅注解头；clientOnly 时追加 value = Dist.CLIENT */
  modBusSubscriber: (modClassName: string, clientOnly: boolean) => string
}

export function resolveMojmapFlavor(loader: 'forge' | 'neoforge', mcVersion: string): MojmapFlavor {
  // 1.20.5 物品组件重构（两加载器同轮生效，经 1.20.4/1.20.6/1.21.1 映射 jar javap 实证）：
  // 工具构造器收窄为 (Tier, Properties)、攻击属性改走 attributeModifiers、
  // FoodProperties.Builder.saturationMod 改名 saturationModifier、
  // ArmorMaterials 成员转 Holder（CHAINMAIL 改名 CHAIN）且耐久迁入 ArmorItem.Type.getDurability(int)
  const itemComponentRefactor = compareMcVersions(mcVersion, '1.20.5') >= 0
  // 1.21.2~1.21.4 过渡时代：Tiers 删除、ToolMaterial record 上位，ArmorMaterials 迁 equipment 包
  const toolMaterialEra =
    compareMcVersions(mcVersion, '1.21.2') >= 0 && compareMcVersions(mcVersion, '1.21.5') < 0
  // 1.21 起资源位置构造器私有化，AttributeModifier 标识从 String 改为 ResourceLocation
  const gte121 = compareMcVersions(mcVersion, '1.21') >= 0
  const saturation = itemComponentRefactor ? 'saturationModifier' : 'saturationMod'
  if (loader === 'forge') {
    return {
      loader,
      holder: 'RegistryObject<Block>',
      holderImport: 'net.minecraftforge.registries.RegistryObject',
      itemHolder: 'RegistryObject',
      itemHolderImport: 'net.minecraftforge.registries.RegistryObject',
      toolViaAttributes: itemComponentRefactor,
      toolCtorNeedsAnon: compareMcVersions(mcVersion, '1.19') < 0,
      blockPropsNeedsMaterial: compareMcVersions(mcVersion, '1.20') < 0,
      armorViaEquipmentSlot: compareMcVersions(mcVersion, '1.20') < 0,
      dataComponentItems: compareMcVersions(mcVersion, '1.21.5') >= 0,
      toolMaterialEra,
      // Forge 侧刷怪蛋类（ForgeSpawnEggItem）26.x 变迁待门禁定位，暂保留旧路径
      spawnEggVanilla: false,
      attributeModifierId: (name) =>
        gte121 ? `ResourceLocation.withDefaultNamespace("${name}")` : `"${name}"`,
      attributeModifierIdImport: gte121 ? 'net.minecraft.resources.ResourceLocation' : null,
      registriesImport: [
        'net.minecraftforge.registries.DeferredRegister',
        'net.minecraftforge.registries.ForgeRegistries'
      ],
      blockRegistryRef: 'ForgeRegistries.BLOCKS',
      itemsRegistryDecl: (mod) =>
        `public static final DeferredRegister<Item> ITEMS =\n        DeferredRegister.create(ForgeRegistries.ITEMS, ${mod}.MOD_ID);`,
      foodSaturation: saturation,
      entityRegistryRef: 'ForgeRegistries.ENTITY_TYPES',
      entityHolder: (cls) => `RegistryObject<EntityType<${cls}>>`,
      entityHolderImport: 'net.minecraftforge.registries.RegistryObject',
      spawnEggClass: 'ForgeSpawnEggItem',
      spawnEggImport: 'net.minecraftforge.common.ForgeSpawnEggItem',
      // 包名对照 forgeTemplates.ts 主类/客户端类已有 import
      eventImports: {
        busSubscriber: 'net.minecraftforge.fml.common.Mod',
        subscribeEvent: 'net.minecraftforge.eventbus.api.SubscribeEvent',
        dist: 'net.minecraftforge.api.distmarker.Dist',
        attributeCreation: 'net.minecraftforge.event.entity.EntityAttributeCreationEvent',
        entityRenderers: 'net.minecraftforge.client.event.EntityRenderersEvent'
      },
      modBusSubscriber: (mod, clientOnly) =>
        `@Mod.EventBusSubscriber(modid = ${mod}.MOD_ID, bus = Mod.EventBusSubscriber.Bus.MOD${clientOnly ? ', value = Dist.CLIENT' : ''})`
    }
  }
  // F4-01：FML 版本断点。FML 2.x（NeoForge 1.20.4 及更早）只有嵌套类
  // net.neoforged.fml.common.Mod.EventBusSubscriber，没有顶层 EventBusSubscriber；
  // FML 3.x+（1.20.5+）才有顶层 EventBusSubscriber。与 neoForgeTemplates.ts 同一条断点。
  const useFml2Nested = compareMcVersions(mcVersion, '1.20.5') < 0
  return {
    loader,
    holder: 'DeferredHolder<Block, Block>',
    holderImport: 'net.neoforged.neoforge.registries.DeferredHolder',
    itemHolder: 'DeferredItem',
    itemHolderImport: 'net.neoforged.neoforge.registries.DeferredItem',
    toolViaAttributes: itemComponentRefactor,
    toolCtorNeedsAnon: compareMcVersions(mcVersion, '1.19') < 0,
    blockPropsNeedsMaterial: compareMcVersions(mcVersion, '1.20') < 0,
    armorViaEquipmentSlot: compareMcVersions(mcVersion, '1.20') < 0,
    dataComponentItems: compareMcVersions(mcVersion, '1.21.5') >= 0,
    toolMaterialEra,
    // NeoForge 21.5+ 移除 DeferredSpawnEggItem（universal jar 实证无此类），回归原版 SpawnEggItem
    spawnEggVanilla: compareMcVersions(mcVersion, '1.21.5') >= 0,
    attributeModifierId: (name) =>
      gte121 ? `ResourceLocation.withDefaultNamespace("${name}")` : `"${name}"`,
    attributeModifierIdImport: gte121 ? 'net.minecraft.resources.ResourceLocation' : null,
    registriesImport: [
      'net.minecraft.core.registries.Registries',
      'net.neoforged.neoforge.registries.DeferredRegister'
    ],
    blockRegistryRef: 'Registries.BLOCK',
    itemsRegistryDecl: (mod) =>
      `public static final DeferredRegister.Items ITEMS =\n        DeferredRegister.createItems(${mod}.MOD_ID);`,
    foodSaturation: saturation,
    entityRegistryRef: 'Registries.ENTITY_TYPE',
    entityHolder: (cls) => `DeferredHolder<EntityType<?>, EntityType<${cls}>>`,
    entityHolderImport: 'net.neoforged.neoforge.registries.DeferredHolder',
    spawnEggClass: 'DeferredSpawnEggItem',
    spawnEggImport: 'net.neoforged.neoforge.common.DeferredSpawnEggItem',
    // 包名对照 neoForgeTemplates.ts 主类/客户端类已有 import
    eventImports: {
      busSubscriber: useFml2Nested
        ? 'net.neoforged.fml.common.Mod'
        : 'net.neoforged.fml.common.EventBusSubscriber',
      subscribeEvent: 'net.neoforged.bus.api.SubscribeEvent',
      dist: 'net.neoforged.api.distmarker.Dist',
      attributeCreation: 'net.neoforged.neoforge.event.entity.EntityAttributeCreationEvent',
      entityRenderers: 'net.neoforged.neoforge.client.event.EntityRenderersEvent'
    },
    // FML loader 9.x（MC 1.21.6 起，pom 实证：21.5.98→loader 7.0.13、21.6.20-beta→9.0.2）
    // 移除 @EventBusSubscriber 的 bus 属性，事件按 IModBusEvent 类型自动路由
    modBusSubscriber: (mod, clientOnly) => {
      const busAttr = compareMcVersions(mcVersion, '1.21.6') >= 0 ? '' : ', bus = EventBusSubscriber.Bus.MOD'
      return useFml2Nested
        ? `@Mod.EventBusSubscriber(modid = ${mod}.MOD_ID, bus = Mod.EventBusSubscriber.Bus.MOD${clientOnly ? ', value = Dist.CLIENT' : ''})`
        : `@EventBusSubscriber(modid = ${mod}.MOD_ID${busAttr}${clientOnly ? ', value = Dist.CLIENT' : ''})`
    }
  }
}

function toJavaConst(id: string): string {
  return id.toUpperCase()
}

function fmtFloat(n: number): string {
  return `${Number(n.toFixed(2))}f`
}

function oneLine(s: string): string {
  return s.replace(/\s+/g, ' ').trim().slice(0, 120)
}

function clampStack(n: number): number {
  if (!Number.isFinite(n)) return 64
  return Math.min(64, Math.max(1, Math.floor(n)))
}

