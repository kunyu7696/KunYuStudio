/**
 * 特性④ GameTest 类生成器（纯函数）。
 *
 * 输入：GameTestSchema 数组 + ModContext（package/modId/modClassName）
 * 输出：Fabric 1.20.1 Yarn 映射的 GameTest .java 类文本
 *
 * 设计：
 * - 一个 modId 对应一个 `<ModClass>GameTests.java`，内含多个 @GameTest 方法
 * - 固定使用 fabric:empty_3x3_3 内置模板，无需手编 .nbt 结构文件
 * - 步骤内 pos 三轴合法范围 0..2（与 3x3x3 模板对齐）
 * - action 映射到 TestContext API：place-block/assert-block/delay 一等支持，
 *   summon-entity 仅生成 vanilla 实体调用；use-item/assert-entity/groovy 在 MVP 阶段
 *   降级为注释占位（避免引用未稳定 API）
 *
 * 安全边界：
 * - 模块名/类名/方法名均由 ModContext + schema.id 派生，无用户自由字符串注入
 * - blockId/entityId 仅匹配白名单 vanilla id，未知 id 降级为注释占位（防误编译失败）
 * - 不写盘（写盘由 contentGenerator 的 sink 负责，便于漂移检测）
 */
import type { GameTestSchema, GameTestStep } from '../../shared/types/content'
import type { ModContext } from './contentGenerator'
import { GAME_TEST_TEMPLATE } from '../../shared/schemas/gametest.schema'

const BANNER =
  'AUTO-GENERATED by KunYu Studio — 请勿手动编辑。\n * 由可视化编辑器根据 .kunyu/content/gametest 语义资产生成，修改请在 GameTest 编辑器中进行。'

/** vanilla 方块 id → Blocks.<FIELD> 映射（白名单，未知 id 降级为注释） */
const VANILLA_BLOCKS: Record<string, { field: string }> = {
  'minecraft:stone': { field: 'Blocks.STONE' },
  'minecraft:dirt': { field: 'Blocks.DIRT' },
  'minecraft:grass_block': { field: 'Blocks.GRASS_BLOCK' },
  'minecraft:cobblestone': { field: 'Blocks.COBBLESTONE' },
  'minecraft:oak_log': { field: 'Blocks.OAK_LOG' },
  'minecraft:oak_planks': { field: 'Blocks.OAK_PLANKS' },
  'minecraft:glass': { field: 'Blocks.GLASS' },
  'minecraft:iron_block': { field: 'Blocks.IRON_BLOCK' },
  'minecraft:gold_block': { field: 'Blocks.GOLD_BLOCK' },
  'minecraft:diamond_block': { field: 'Blocks.DIAMOND_BLOCK' },
  'minecraft:bedrock': { field: 'Blocks.BEDROCK' },
  'minecraft:air': { field: 'Blocks.AIR' }
}

/** vanilla 实体 id → EntityType.<FIELD> 映射（白名单） */
const VANILLA_ENTITIES: Record<string, { field: string }> = {
  'minecraft:cow': { field: 'EntityType.COW' },
  'minecraft:pig': { field: 'EntityType.PIG' },
  'minecraft:chicken': { field: 'EntityType.CHICKEN' },
  'minecraft:sheep': { field: 'EntityType.SHEEP' },
  'minecraft:zombie': { field: 'EntityType.ZOMBIE' },
  'minecraft:skeleton': { field: 'EntityType.SKELETON' },
  'minecraft:creeper': { field: 'EntityType.CREEPER' },
  'minecraft:villager': { field: 'EntityType.VILLAGER' }
}

interface JavaField {
  /** 完整字段表达式，如 "Blocks.STONE" */
  expr: string
}

/** 把方块 id 解析为 Blocks.<FIELD>；未知 id 返回 null（调用方降级为注释） */
function resolveBlock(blockId: string): JavaField | null {
  const id = blockId.startsWith('minecraft:') ? blockId : `minecraft:${blockId}`
  const entry = VANILLA_BLOCKS[id]
  return entry ? { expr: entry.field } : null
}

/** 把实体 id 解析为 EntityType.<FIELD>；未知 id 返回 null */
function resolveEntity(entityId: string): JavaField | null {
  const id = entityId.startsWith('minecraft:') ? entityId : `minecraft:${entityId}`
  const entry = VANILLA_ENTITIES[id]
  return entry ? { expr: entry.field } : null
}

interface StepJava {
  /** 生成的 Java 语句（已含缩进与换行），失败时为空字符串 */
  code: string
  /** 降级为注释时的提示文本 */
  warn?: string
}

function posLiteral(pos: [number, number, number] | undefined): string {
  if (!pos) return 'new BlockPos(0, 0, 0)'
  return `new BlockPos(${pos[0]}, ${pos[1]}, ${pos[2]})`
}

function indent(text: string, level: number): string {
  const pad = ' '.repeat(level * 4)
  return text
    .split('\n')
    .map((l) => (l ? pad + l : l))
    .join('\n')
}

/** 把单个 step 转换为 Java 语句（已缩进 3 级 = 方法体内） */
function stepToJava(step: GameTestStep): StepJava {
  const pos = posLiteral(step.pos)
  const args = step.args ?? {}
  switch (step.action) {
    case 'place-block': {
      const blockId = typeof args['block'] === 'string' ? (args['block'] as string) : ''
      const field = resolveBlock(blockId)
      if (!field) {
        return {
          code: indent(`// TODO place-block: 未识别方块 id "${blockId}"，请用白名单内的 vanilla id 或手编注册`, 3),
          warn: `未识别方块 ${blockId}`
        }
      }
      return { code: indent(`ctx.setBlockState(${pos}, ${field.expr}.getDefaultState());`, 3) }
    }
    case 'assert-block': {
      const blockId = typeof args['block'] === 'string' ? (args['block'] as string) : ''
      const field = resolveBlock(blockId)
      if (!field) {
        return {
          code: indent(`// TODO assert-block: 未识别方块 id "${blockId}"`, 3),
          warn: `未识别方块 ${blockId}`
        }
      }
      return { code: indent(`ctx.expectBlock(${field.expr}, ${pos});`, 3) }
    }
    case 'summon-entity': {
      const entityId = typeof args['entity'] === 'string' ? (args['entity'] as string) : ''
      const field = resolveEntity(entityId)
      if (!field) {
        return {
          code: indent(`// TODO summon-entity: 未识别实体 id "${entityId}"`, 3),
          warn: `未识别实体 ${entityId}`
        }
      }
      return { code: indent(`ctx.spawnEntity(${field.expr}, ${pos});`, 3) }
    }
    case 'delay': {
      const ticks = typeof args['ticks'] === 'number' ? Math.max(1, Math.floor(args['ticks'] as number)) : 10
      return { code: indent(`ctx.waitTicks(${ticks});`, 3) }
    }
    case 'use-item': {
      return {
        code: indent(`// TODO use-item: MVP 不生成物品使用代码，请在手编中补全`, 3),
        warn: 'use-item MVP 占位'
      }
    }
    case 'assert-entity': {
      return {
        code: indent(`// TODO assert-entity: MVP 不生成实体断言代码`, 3),
        warn: 'assert-entity MVP 占位'
      }
    }
    case 'groovy': {
      const code = typeof args['code'] === 'string' ? (args['code'] as string) : ''
      const snippet = code.replace(/\*\//g, '*\\/').slice(0, 200)
      return {
        code: indent(`// groovy 转译占位（GameTest 不支持运行时 Groovy，请在 Java 中手编等价逻辑）：\n// ${snippet.replace(/\n/g, '\n// ')}`, 3),
        warn: 'groovy 转译占位'
      }
    }
    default:
      return { code: indent(`// 未知 action：${step.action}`, 3), warn: `未知 action ${step.action}` }
  }
}

/**
 * 把单个 schema 转换为 @GameTest 方法（含注解、方法签名、Arrange/Act/Assert 注释段、ctx.complete() 收尾）。
 * 方法名 test_<id>；@GameTest 用 fabric:empty_3x3_3 内置模板。
 */
function schemaToMethod(schema: GameTestSchema): string {
  const methodName = `test_${schema.id}`
  const timeout = schema.timeoutTicks ?? 200
  const lines: string[] = []
  lines.push(`    @GameTest(template = "${GAME_TEST_TEMPLATE}", timeoutTicks = ${timeout})`)
  lines.push(`    public static void ${methodName}(TestContext ctx) throws Exception {`)

  const phaseLabels: Record<string, string> = {
    arrange: 'Arrange',
    act: 'Act',
    assert: 'Assert'
  }
  let lastPhase = ''
  for (const step of schema.steps) {
    if (step.phase !== lastPhase) {
      if (lastPhase) lines.push('')
      lines.push(`        // ${phaseLabels[step.phase] ?? step.phase}`)
      lastPhase = step.phase
    }
    if (step.name) {
      lines.push(`        // ${step.name}`)
    }
    const j = stepToJava(step)
    if (j.code) lines.push(j.code)
  }
  lines.push('        ctx.complete();')
  lines.push('    }')
  return lines.join('\n')
}

/**
 * 把多个 schema 合并生成一个 `<ModClass>GameTests.java` 文件。
 * - 空 schemas 数组返回空串（调用方决定是否落盘）
 * - 每个方法对应一个 schema；类名固定 `<ModClass>GameTests`
 */
export function generateGameTestClasses(schemas: GameTestSchema[], ctx: ModContext): string {
  if (schemas.length === 0) return ''
  const className = `${ctx.modClassName}GameTests`
  const methods = schemas.map(schemaToMethod).join('\n\n')

  return `package ${ctx.packageName}.gametest;

/*
 * ${BANNER}
 */

import net.minecraft.test.GameTest;
import net.minecraft.test.TestContext;
import net.minecraft.block.Blocks;
import net.minecraft.util.math.BlockPos;
import net.minecraft.entity.EntityType;

public class ${className} {

${methods}
}
`
}

/**
 * 计算生成 Java 文件相对项目根的 POSIX 路径（src/test/java/<pkg>/gametest/<Class>.java）。
 * 由 contentGenerator 调用决定落盘位置，不直接写盘。
 */
export function gameTestJavaRelPath(ctx: ModContext): string {
  const className = `${ctx.modClassName}GameTests`
  return `src/test/java/${ctx.pkgPath}/gametest/${className}.java`
}

/**
 * 列出本次生成需要的所有 Java 导入（仅 diagnostics/调试用，实际导入已写死在类模板里）。
 */
export function listGameTestImports(): string[] {
  return [
    'net.minecraft.test.GameTest',
    'net.minecraft.test.TestContext',
    'net.minecraft.block.Blocks',
    'net.minecraft.util.math.BlockPos',
    'net.minecraft.entity.EntityType'
  ]
}
