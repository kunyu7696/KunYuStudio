/** 属性注册织入类：EntityAttributeCreationEvent 逐实体登记 createAttributes */
export function mojmapEntitySetupJava(ctx: ModContext, entities: EntitySchema[]): string {
  const f = resolveMojmapFlavor(ctx.loader === 'neoforge' ? 'neoforge' : 'forge', ctx.mcVersion)
  const puts = entities
    .map(
      (e) =>
        `        event.put(ModEntities.${toJavaConst(e.id)}.get(), ${mojmapEntityClassName(e)}.createAttributes().build());`
    )
    .join('\n')

  return `package ${ctx.packageName}.entity;

import ${ctx.packageName}.${ctx.modClassName};
import ${ctx.packageName}.registry.ModEntities;
import ${f.eventImports.attributeCreation};
import ${f.eventImports.busSubscriber};
import ${f.eventImports.subscribeEvent};

/**
 * ${GENERATED_BANNER}
 */
${f.modBusSubscriber(ctx.modClassName, false)}
public class ModEntitySetup {
    @SubscribeEvent
    public static void onEntityAttributeCreation(EntityAttributeCreationEvent event) {
${puts}
    }
}
`
}

/** 客户端渲染织入类：注册实体渲染器与模型层（仅 Dist.CLIENT） */
export function mojmapClientEntitySetupJava(ctx: ModContext, entities: EntitySchema[]): string {
  const f = resolveMojmapFlavor(ctx.loader === 'neoforge' ? 'neoforge' : 'forge', ctx.mcVersion)
  const rendererRegs = entities
    .map(
      (e) =>
        `        event.registerEntityRenderer(ModEntities.${toJavaConst(e.id)}.get(), ${mojmapEntityRendererClassName(e)}::new);`
    )
    .join('\n')
  const layerRegs = entities
    .map(
      (e) =>
        `        event.registerLayerDefinition(${mojmapEntityRendererClassName(e)}.MODEL_LAYER, ${mojmapEntityModelClassName(e)}::createBodyLayer);`
    )
    .join('\n')

  return `package ${ctx.packageName}.entity;

import ${ctx.packageName}.${ctx.modClassName};
import ${ctx.packageName}.registry.ModEntities;
import ${f.eventImports.busSubscriber};
import ${f.eventImports.dist};
import ${f.eventImports.entityRenderers};
import ${f.eventImports.subscribeEvent};

/**
 * ${GENERATED_BANNER}
 */
${f.modBusSubscriber(ctx.modClassName, true)}
public class ClientEntitySetup {
    @SubscribeEvent
    public static void onRegisterRenderers(EntityRenderersEvent.RegisterRenderers event) {
${rendererRegs}
    }

    @SubscribeEvent
    public static void onRegisterLayerDefinitions(EntityRenderersEvent.RegisterLayerDefinitions event) {
${layerRegs}
    }
}
`
}
