import { autoUvAllBox } from '../../shared/utils/cubeModel'
import { resolveMojmapFlavor } from './mojmapCodegen'
import type { ModContext } from './contentGenerator'

const GENERATED_BANNER =
  'AUTO-GENERATED by KunYu Studio — 请勿手动编辑。\n * 由可视化编辑器根据 .kunyu/content 语义资产生成，修改请在可视化编辑器中进行。'

/** id → PascalCase 类名片段（goblin_knight → GoblinKnight）；镜像 contentGenerator.pascal */
function pascal(id: string): string {
  return id
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join('')
}

function toJavaConst(id: string): string {
  return id.toUpperCase()
}

function fmtFloat(n: number): string {
  return `${Number(n.toFixed(2))}f`
}

/** 1.20.x 及更早 Mojmap API（ResourceLocation 公有构造器 / float RGBA renderToBuffer）；1.21 起为新 API */
export function isLegacyMojmapApi(mcVersion: string): boolean {
  const m = /^1\.(\d+)/.exec(mcVersion)
  return m ? Number(m[1]) <= 20 : true
}

/** 实体类名（goblin → GoblinEntity），供 contentGenerator 计算落盘路径复用 */
export function mojmapEntityClassName(e: EntitySchema): string {
  return `${pascal(e.id)}Entity`
}

/** 实体模型类名（goblin → GoblinModel） */
export function mojmapEntityModelClassName(e: EntitySchema): string {
  return `${pascal(e.id)}Model`
}

/** 实体渲染器类名（goblin → GoblinRenderer） */
export function mojmapEntityRendererClassName(e: EntitySchema): string {
  return `${pascal(e.id)}Renderer`
}

