interface CuboidSpec {
  uv0: number
  uv1: number
  x: number
  y: number
  z: number
  sx: number
  sy: number
  sz: number
}

/**
 * cube elements（贴图像素单位）→ 实体 cuboid（16 像素单位，根部件 pivot 8,24,8）。
 * 坐标数学严格镜像 contentGenerator.elementsToCuboids（Yarn 分支），
 * 仅下游消费方式不同（CubeListBuilder.addBox / PartPose.offset）。
 */
function elementsToCuboids(elements: CubeElement[], canvasSize: number): CuboidSpec[] {
  // 强制 box-uv 布局，保证 cuboid(u,v) 与贴图像素精确对应
  const laid = autoUvAllBox(elements, canvasSize)
  const k = 16 / canvasSize
  return laid.map((el) => {
    const [fx, fy, fz] = el.from
    const [tx, ty, tz] = el.to
    const dz = Math.max(0, tz - fz)
    const north = el.faces.north?.uv
    // box 布局中 north = [x+dz, y+dz, ...]，cuboid 原点回退 dz
    const uv0 = north ? north[0] - dz : 0
    const uv1 = north ? north[1] - dz : 0
    return {
      uv0,
      uv1,
      x: fx * k - 8,
      y: 24 - ty * k,
      z: fz * k - 8,
      sx: (tx - fx) * k,
      sy: (ty - fy) * k,
      sz: dz * k
    }
  })
}

/**
 * 实体模型类 Java：cube elements → CubeListBuilder cuboid 链。
 * 镜像 fabricEntityModelJava：Yarn ModelPartBuilder.cuboid → Mojmap CubeListBuilder.addBox、
 * ModelTransform.pivot(8,24,8) → PartPose.offset(8,24,8)（纯平移 pivot 等价换算）。
 */
export function mojmapEntityModelJava(
  ctx: ModContext,
  e: EntitySchema,
  cube: { textureSize: number; elements: CubeElement[] }
): string {
  const cls = mojmapEntityModelClassName(e)
  const entCls = mojmapEntityClassName(e)
  const cuboids = elementsToCuboids(cube.elements, cube.textureSize)
  // 1.21 起 Model.renderToBuffer/ModelPart.render 末参由 float RGBA 改为 int ARGB 颜色
  const legacyRender = isLegacyMojmapApi(ctx.mcVersion)
  const childLines = cuboids
    .map(
      (c, i) =>
        `        part.addOrReplaceChild("part${i}",
            CubeListBuilder.create()
                .texOffs(${c.uv0}, ${c.uv1})
                .addBox(${[c.x, c.y, c.z, c.sx, c.sy, c.sz].map(fmtFloat).join(', ')}),
            PartPose.offset(8.0f, 24.0f, 8.0f));`
    )
    .join('\n')

  return `package ${ctx.packageName}.entity;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;

/**
 * ${GENERATED_BANNER}
 */
public class ${cls} extends EntityModel<${entCls}> {
    private final ModelPart root;

    public ${cls}(ModelPart root) {
        this.root = root;
    }

    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition part = mesh.getRoot();
${childLines}
        return LayerDefinition.create(mesh, ${cube.textureSize}, ${cube.textureSize});
    }

    @Override
    public void setupAnim(${entCls} entity, float limbSwing, float limbSwingAmount,
                          float ageInTicks, float netHeadYaw, float headPitch) {
    }

    // 1.20.x 签名（float RGBA）；1.21 起末参改为 int ARGB 颜色（NeoForge 1.21.1 真机编译验证）
${legacyRender
    ? `    @Override
    public void renderToBuffer(PoseStack poseStack, VertexConsumer buffer, int packedLight,
                               int packedOverlay, float red, float green, float blue, float alpha) {
        this.root.render(poseStack, buffer, packedLight, packedOverlay, red, green, blue, alpha);
    }`
    : `    @Override
    public void renderToBuffer(PoseStack poseStack, VertexConsumer buffer, int packedLight,
                               int packedOverlay, int color) {
        this.root.render(poseStack, buffer, packedLight, packedOverlay, color);
    }`}
}
`
}

/** 实体渲染器类 Java（MobRenderer + 静态 MODEL_LAYER 供 ClientEntitySetup 注册） */
export function mojmapEntityRendererJava(ctx: ModContext, e: EntitySchema): string {
  const cls = mojmapEntityRendererClassName(e)
  const entCls = mojmapEntityClassName(e)
  const modelCls = mojmapEntityModelClassName(e)
  // 1.21 起 ResourceLocation 构造器转私有，必须用 fromNamespaceAndPath（NeoForge 1.21.1 真机编译验证）
  const loc = (path: string): string =>
    isLegacyMojmapApi(ctx.mcVersion)
      ? `new ResourceLocation("${ctx.modId}", "${path}")`
      : `ResourceLocation.fromNamespaceAndPath("${ctx.modId}", "${path}")`
  return `package ${ctx.packageName}.entity;

import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.client.renderer.entity.MobRenderer;
import net.minecraft.resources.ResourceLocation;

/**
 * ${GENERATED_BANNER}
 */
public class ${cls} extends MobRenderer<${entCls}, ${modelCls}> {
    public static final ModelLayerLocation MODEL_LAYER =
        new ModelLayerLocation(${loc(e.id)}, "main");
    private static final ResourceLocation TEXTURE = ${loc(`textures/entity/${e.id}.png`)};

    public ${cls}(EntityRendererProvider.Context context) {
        super(context, new ${modelCls}(context.bakeLayer(MODEL_LAYER)), 0.5f);
    }

    @Override
    public ResourceLocation getTextureLocation(${entCls} entity) {
        return TEXTURE;
    }
}
`
}

