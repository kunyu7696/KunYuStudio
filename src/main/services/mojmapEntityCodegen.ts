/**
 * 翻译单个 goalSelector 目标为 Mojmap goal 表达式；基类不兼容时返回 null。
 * 分支与基类限制逐一对应 contentGenerator.fabricGoalExpr：
 * PanicGoal/RandomStrollGoal/MeleeAttackGoal 构造参数要求 PathfinderMob，
 * Mob 基类（baseClass 'Entity'）不兼容；BreedGoal/FollowParentGoal 仅 Animal。
 */
function mojmapGoalExpr(base: MojmapEntityBase, g: AiGoal): string | null {
  const spd = (key: string, dflt: number): string => fmtFloat(Number(g.params[key] ?? dflt))
  switch (g.type) {
    case 'swim':
      return 'new FloatGoal(this)'
    case 'panic':
      return base === 'Mob' ? null : `new PanicGoal(this, ${spd('speed', 1.5)})`
    case 'wander':
      return base === 'Mob' ? null : `new RandomStrollGoal(this, ${spd('speed', 0.8)})`
    case 'look_at':
      return `new LookAtPlayerGoal(this, Player.class, ${Number(g.params.range ?? 8)}.0f)`
    case 'melee_attack':
      // MeleeAttackGoal 构造参数为 PathfinderMob，Mob 基类不兼容
      return base === 'Mob'
        ? null
        : `new MeleeAttackGoal(this, ${spd('speed', 1.0)}, ${g.params.pauseWhenIdle === true})`
    case 'eat_grass':
      return 'new EatGrassGoal(this)'
    case 'mate':
      return base === 'Animal' ? `new BreedGoal(this, ${spd('speed', 1.0)})` : null
    case 'follow_parent':
      return base === 'Animal' ? `new FollowParentGoal(this, ${spd('speed', 1.0)})` : null
    // follow_target 需 TamableAnimal、avoid_water 仅语义：跳过
    default:
      return null
  }
}

/** 翻译单个 targetSelector 目标（对应 fabricTargetExpr）；不兼容时返回 null */
function mojmapTargetExpr(t: AiTarget): string | null {
  if (t.type === 'attack_player') {
    return 'new NearestAttackableTargetGoal<>(this, Player.class, true)'
  }
  return null
}

/** 实体属性 → Java .add 链（零值属性省略，交由原版默认；镜像 fabricEntityAttrLines） */
function mojmapEntityAttrLines(e: EntitySchema): string[] {
  const a = e.attributes
  const lines = [
    `        .add(Attributes.MAX_HEALTH, ${fmtFloat(a.maxHealth)})`,
    `        .add(Attributes.MOVEMENT_SPEED, ${fmtFloat(a.movementSpeed)})`,
    `        .add(Attributes.FOLLOW_RANGE, ${fmtFloat(a.followRange)})`
  ]
  if (a.attackDamage > 0)
    lines.push(`        .add(Attributes.ATTACK_DAMAGE, ${fmtFloat(a.attackDamage)})`)
  if (a.armor > 0) lines.push(`        .add(Attributes.ARMOR, ${fmtFloat(a.armor)})`)
  if (a.knockbackResistance > 0)
    lines.push(
      `        .add(Attributes.KNOCKBACK_RESISTANCE, ${fmtFloat(a.knockbackResistance)})`
    )
  return lines
}

/**
 * 实体主类 Java。
 * @param geoFallback true 表示原定义为 blockbench_geo（GeckoLib）实体；
 *                    Mojmap 分支暂不支持 GeckoLib，已按静态 cube 模型生成，头部注释显式标注。
 */
export function mojmapEntityJava(ctx: ModContext, e: EntitySchema, geoFallback = false): string {
  const base = mojmapEntityBase(e)
  const cls = mojmapEntityClassName(e)

  const goalLines: string[] = []
  for (const g of e.ai.goals) {
    const expr = mojmapGoalExpr(base, g)
    if (expr) goalLines.push(`        this.goalSelector.addGoal(${g.priority ?? 0}, ${expr});`)
  }
  for (const t of e.ai.targets) {
    const expr = mojmapTargetExpr(t)
    if (expr) goalLines.push(`        this.targetSelector.addGoal(${t.priority ?? 0}, ${expr});`)
  }

  const isAnimal = base === 'Animal'
  const imports = [
    `import ${MOJMAP_BASE_IMPORT[base]};`,
    'import net.minecraft.world.entity.EntityType;',
    'import net.minecraft.world.entity.ai.attributes.AttributeSupplier;',
    'import net.minecraft.world.entity.ai.attributes.Attributes;',
    'import net.minecraft.world.entity.ai.goal.*;',
    'import net.minecraft.world.entity.ai.goal.target.NearestAttackableTargetGoal;',
    'import net.minecraft.world.entity.player.Player;',
    'import net.minecraft.world.level.Level;'
  ]
  // Mob 基类以外的属性工厂同样需要 Mob 符号（Mob.createMobAttributes）
  if (MOJMAP_ATTR_FACTORY[base].startsWith('Mob.') && base !== 'Mob') {
    imports.push('import net.minecraft.world.entity.Mob;')
  }
  if (isAnimal) {
    imports.push(
      'import net.minecraft.server.level.ServerLevel;',
      'import net.minecraft.world.entity.AgeableMob;',
      'import net.minecraft.world.item.ItemStack;',
      'import org.jetbrains.annotations.Nullable;'
    )
  }

  // 繁殖语义对齐 fabric 版：不可喂食、createChild（Mojmap getBreedOffspring）返回 null
  const animalMethods = `
    @Override
    public boolean isFood(ItemStack stack) {
        return false;
    }

    @Nullable
    @Override
    public AgeableMob getBreedOffspring(ServerLevel level, AgeableMob partner) {
        return null;
    }
`

  const geoNote = geoFallback
    ? '\n * 注意：原定义为 Blockbench/GeckoLib 骨骼动画实体；Mojmap（Forge/NeoForge）实体暂不支持 GeckoLib，已按静态 cube 模型生成。'
    : ''

  return `package ${ctx.packageName}.entity;

${imports.join('\n')}

/**
 * ${GENERATED_BANNER}${geoNote}
 */
public class ${cls} extends ${base} {
    public ${cls}(EntityType<? extends ${base}> type, Level level) {
        super(type, level);
    }

    @Override
    protected void registerGoals() {
${goalLines.join('\n') || '        // 无 AI 目标'}
    }

    public static AttributeSupplier.Builder createAttributes() {
        return ${MOJMAP_ATTR_FACTORY[base]}()
${mojmapEntityAttrLines(e).join('\n')};
    }
${isAnimal ? animalMethods : ''}}
`
}

