type MojmapEntityBase = 'Animal' | 'PathfinderMob' | 'Monster' | 'Mob'

/**
 * EntitySchema 基类语义 → Mojmap Java 基类（镜像 fabric entityJavaBase 的分支）：
 * baseClass 'Monster' → Monster；baseClass 'Entity' → Mob；
 * 其余（PathAwareEntity 语义）：被动生物用 Animal 获得繁殖基础设施，否则 PathfinderMob。
 */
function mojmapEntityBase(e: EntitySchema): MojmapEntityBase {
  if (e.baseClass === 'Monster') return 'Monster'
  if (e.baseClass === 'Entity') return 'Mob'
  return e.entityType === 'passive' ? 'Animal' : 'PathfinderMob'
}

const MOJMAP_BASE_IMPORT: Record<MojmapEntityBase, string> = {
  Animal: 'net.minecraft.world.entity.animal.Animal',
  PathfinderMob: 'net.minecraft.world.entity.PathfinderMob',
  Monster: 'net.minecraft.world.entity.monster.Monster',
  Mob: 'net.minecraft.world.entity.Mob'
}

/** createAttributes 的属性工厂（Monster 用怪物默认集，其余用生物默认集） */
const MOJMAP_ATTR_FACTORY: Record<MojmapEntityBase, string> = {
  Animal: 'Mob.createMobAttributes',
  PathfinderMob: 'Mob.createMobAttributes',
  Monster: 'Monster.createMonsterAttributes',
  Mob: 'Mob.createMobAttributes'
}

/** EntitySchema 语义 → MobCategory：被动/中立→CREATURE、敌对→MONSTER、其余 MISC */
function mojmapMobCategory(e: EntitySchema): string {
  if (e.entityType === 'passive' || e.entityType === 'neutral') return 'CREATURE'
  if (e.entityType === 'hostile') return 'MONSTER'
  return 'MISC'
}

