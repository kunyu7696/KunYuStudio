/**
 * 附魔代码/数据生成（与 mojmapCodegen 平行的版相关适配层）。
 *
 * 路线分流（与 ai-reference/templates 下的附魔模板对齐）：
 * - Fabric 1.20.1（Yarn）：Registry.register(Registries.ENCHANTMENT, …) + 静态内部子类
 * - Forge 1.20.1（Mojmap）：DeferredRegister(ForgeRegistries.ENCHANTMENTS) + RegistryObject
 * - NeoForge 1.20.x（Mojmap）：DeferredRegister(Registries.ENCHANTMENT) + DeferredHolder
 * - 1.21+（Fabric/Forge/NeoForge）：附魔数据驱动，零 Java，输出 data/<ns>/enchantment/<id>.json
 *
 * 主类织入（register 挂载）由 contentGenerator 的 sync 函数负责，本模块只产出注册类/JSON 本体。
 */
