/** Enchantment.Rarity → 1.21 JSON weight（原版权重表） */
const RARITY_WEIGHT: Record<EnchantmentRarity, number> = {
  COMMON: 10,
  UNCOMMON: 5,
  RARE: 2,
  VERY_RARE: 1
}

function pascal(id: string): string {
  return id
    .split('_')
    .filter(Boolean)
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join('')
}

function fmtFloat(n: number): string {
  return `${Number(n.toFixed(2))}f`
}

function oneLine(s: string): string {
  return s.replace(/\s+/g, ' ').trim().slice(0, 120)
}

/**
 * 数据驱动路线判定：1.21 起附魔为数据包注册表（data/<ns>/enchantment/*.json），
 * 与加载器无关——Fabric/Forge/NeoForge 均由原版数据包机制加载，不再生成
 * 1.21 已删除的 EnchantmentTarget/EnchantmentCategory Java 路线。
 */
export function isDataDrivenEnchantment(ctx: ModContext): boolean {
  return isMc121OrLater(ctx.mcVersion)
}

