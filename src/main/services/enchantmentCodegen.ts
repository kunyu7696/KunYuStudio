function mojmapModEnchantmentsJava(ctx: ModContext, list: EnchantmentSchema[]): string {
  const f = resolveMojmapFlavor(ctx.loader === 'neoforge' ? 'neoforge' : 'forge', ctx.mcVersion)
  const isForge = ctx.loader === 'forge'
  const holderType = isForge ? 'RegistryObject<Enchantment>' : 'DeferredHolder<Enchantment, Enchantment>'
  const registryRef = isForge ? 'ForgeRegistries.ENCHANTMENTS' : 'Registries.ENCHANTMENT'
  const needMobType = list.some((e) => e.damageBonus)

  const fields = list
    .map(
      (e) => `    /** ${oneLine(e.displayName.zh_cn || e.displayName.en_us || e.id)} */
    public static final ${holderType} ${e.id.toUpperCase()} =
            ENCHANTMENTS.register("${e.id}", ${pascal(e.id)}Enchantment::new);`
    )
    .join('\n\n')

  const classes = list
    .map((e) => {
      const lines: string[] = [
        `        public ${pascal(e.id)}Enchantment() {`,
        `            super(Enchantment.Rarity.${e.rarity}, EnchantmentCategory.${MOJMAP_TARGET[e.target]}, ${yarnSlots(
          e.slots
        )});`,
        '        }',
        '',
        '        @Override',
        '        public int getMinCost(int level) {',
        `            return ${e.minCostBase} + (level - 1) * ${e.minCostPerLevel};`,
        '        }',
        '',
        '        @Override',
        '        public int getMaxCost(int level) {',
        `            return getMinCost(level) + ${e.maxCostExtra};`,
        '        }',
        '',
        '        @Override',
        '        public int getMaxLevel() {',
        `            return ${e.maxLevel};`,
        '        }'
      ]
      if (e.treasure) {
        lines.push(
          '',
          '        @Override',
          '        public boolean isTreasureOnly() {',
          '            return true;',
          '        }'
        )
      }
      if (e.curse) {
        lines.push('', '        @Override', '        public boolean isCurse() {', '            return true;', '        }')
      }
      if (e.damageBonus) {
        lines.push(
          '',
          '        @Override',
          '        public float getDamageBonus(int level, MobType mobType) {',
          `            return ${fmtFloat(e.damageBonus.base)} + ${fmtFloat(e.damageBonus.perLevel)} * (level - 1);`,
          '        }'
        )
      }
      return `    public static class ${pascal(e.id)}Enchantment extends Enchantment {
${lines.join('\n')}
    }`
    })
    .join('\n\n')

  return `package ${ctx.packageName}.registry;

import ${ctx.packageName}.${ctx.modClassName};
${f.registriesImport.map((i) => `import ${i};`).join('\n')}
import ${f.holderImport};
import net.minecraft.world.entity.EquipmentSlot;
${needMobType ? 'import net.minecraft.world.entity.MobType;\n' : ''}import net.minecraft.world.item.enchantment.Enchantment;
import net.minecraft.world.item.enchantment.EnchantmentCategory;

/**
 * ${GENERATED_BANNER}
 */
public class ModEnchantments {
    public static final DeferredRegister<Enchantment> ENCHANTMENTS =
            DeferredRegister.create(${registryRef}, ${ctx.modClassName}.MOD_ID);

${fields || '    // 暂无由可视化编辑器管理的附魔'}

${classes}
}
`
}

/** 生成 ModEnchantments.java（按加载器分发 Yarn / Mojmap） */
export function generateModEnchantmentsJava(
  ctx: ModContext,
  list: EnchantmentSchema[]
): string {
  return ctx.loader === 'fabric'
    ? fabricModEnchantmentsJava(ctx, list)
    : mojmapModEnchantmentsJava(ctx, list)
}

