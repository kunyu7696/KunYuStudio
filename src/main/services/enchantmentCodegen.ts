/** 编译为 1.21 enchantment 注册表 JSON（普通对象，调用方负责序列化） */
export function compileEnchantmentJson(
  ctx: ModContext,
  e: EnchantmentSchema
): Record<string, unknown> {
  const json: Record<string, unknown> = {
    description: { translate: `enchantment.${ctx.modId}.${e.id}` },
    supported_items: `#minecraft:enchantable/${ENCHANTABLE_TAG[e.target]}`,
    weight: RARITY_WEIGHT[e.rarity],
    max_level: e.maxLevel,
    // Java 路线 getMaxPower = getMinPower(level) + maxCostExtra，等价于 base 整体平移
    min_cost: { base: e.minCostBase, per_level_above_first: e.minCostPerLevel },
    max_cost: {
      base: e.minCostBase + e.maxCostExtra,
      per_level_above_first: e.minCostPerLevel
    },
    anvil_cost: e.anvilCost,
    slots: [...e.slots]
  }
  if (e.damageBonus) {
    json.effects = {
      'minecraft:damage': [
        {
          effect: {
            type: 'minecraft:add',
            value: {
              type: 'minecraft:linear',
              base: e.damageBonus.base,
              per_level_above_first: e.damageBonus.perLevel
            }
          }
        }
      ]
    }
  }
  return json
}
