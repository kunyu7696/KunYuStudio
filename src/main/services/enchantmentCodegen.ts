/**
 * 生成 Enchantment 构造器第三参数（EquipmentSlot[]）的 Java 字面量。
 *
 * Yarn 1.20.1 Enchantment 构造器签名为
 *   protected Enchantment(Rarity, EnchantmentTarget, EquipmentSlot[])
 * 第三参数是显式数组（非 varargs），必须用 `new EquipmentSlot[]{...}` 包裹，
 * 直接传单个 `EquipmentSlot.MAINHAND` 会触发「无法转换为 EquipmentSlot[]」编译错误。
 */
function yarnSlots(slots: EnchantmentSlot[]): string {
  const items = slots.map((s) => `EquipmentSlot.${s.toUpperCase()}`).join(', ')
  return `new EquipmentSlot[]{${items}}`
}

function fabricModEnchantmentsJava(ctx: ModContext, list: EnchantmentSchema[]): string {
  const needEntityGroup = list.some((e) => e.damageBonus)
  const enchRegConst = registriesConst(ctx.mcVersion, 'ENCHANTMENT')
  const fields = list
    .map(
      (e) => `    /** ${oneLine(e.displayName.zh_cn || e.displayName.en_us || e.id)} */
    public static final Enchantment ${e.id.toUpperCase()} = Registry.register(
        ${enchRegConst},
        ${ctx.modClassName}.id("${e.id}"),
        new ${pascal(e.id)}Enchantment()
    );`
    )
    .join('\n\n')

  const classes = list
    .map((e) => {
      const lines: string[] = [
        `        public ${pascal(e.id)}Enchantment() {`,
        `            super(Enchantment.Rarity.${e.rarity}, EnchantmentTarget.${YARN_TARGET[e.target]}, ${yarnSlots(
          e.slots
        )});`,
        '        }',
        '',
        '        @Override',
        '        public int getMinPower(int level) {',
        `            return ${e.minCostBase} + (level - 1) * ${e.minCostPerLevel};`,
        '        }',
        '',
        '        @Override',
        '        public int getMaxPower(int level) {',
        `            return super.getMinPower(level) + ${e.maxCostExtra};`,
        '        }',
        '',
        '        @Override',
        '        public int getMaxLevel() {',
        `            return ${e.maxLevel};`,
        '        }'
      ]
      if (e.treasure) {
        lines.push('', '        @Override', '        public boolean isTreasure() {', '            return true;', '        }')
      }
      if (e.curse) {
        lines.push('', '        @Override', '        public boolean isCursed() {', '            return true;', '        }')
      }
      if (e.damageBonus) {
        lines.push(
          '',
          '        @Override',
          '        public float getAttackDamage(int level, EntityGroup group) {',
          `            return ${fmtFloat(e.damageBonus.base)} + ${fmtFloat(e.damageBonus.perLevel)} * (level - 1);`,
          '        }'
        )
      }
      return `    public static class ${pascal(e.id)}Enchantment extends Enchantment {
${lines.join('\n')}
    }`
    })
    .join('\n\n')

  return `package ${ctx.packageName}.registry;

import ${ctx.packageName}.${ctx.modClassName};
import net.minecraft.enchantment.Enchantment;
import net.minecraft.enchantment.EnchantmentTarget;
import net.minecraft.entity.EquipmentSlot;
${needEntityGroup ? 'import net.minecraft.entity.EntityGroup;\n' : ''}${registryImports(ctx.mcVersion)}
/**
 * ${GENERATED_BANNER}
 */
public class ModEnchantments {
${fields || '    // 暂无由可视化编辑器管理的附魔'}

    /** 由主类 onInitialize 调用，触发本类加载与上方字段注册 */
    public static void register() {
    }

${classes}
}
`
}

