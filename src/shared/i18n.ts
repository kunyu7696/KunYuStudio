/** 设置共享层语言（渲染层 setLocale 与主进程设置链路同步调用） */
export function setSharedLocale(locale: SharedLocale): void {
  currentLocale = locale
}

/** 当前共享层语言 */
export function getSharedLocale(): SharedLocale {
  return currentLocale
}

type MessageTree = typeof zhCN

function lookup(catalog: MessageTree, key: string): string | null {
  let node: unknown = catalog
  for (const seg of key.split('.')) {
    if (!node || typeof node !== 'object') return null
    node = (node as Record<string, unknown>)[seg]
  }
  return typeof node === 'string' ? node : null
}

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (m, name: string) =>
    name in params ? String(params[name]) : m
  )
}

/**
 * 翻译 schema 命名空间键。
 * @param locale 显式语言（可选；渲染层 computed 传入响应式 locale 以建立依赖）
 * 回退顺序：指定/当前语言目录 → zh-CN → 键名本身。
 */
export function sharedT(
  key: string,
  params?: Record<string, string | number>,
  locale?: SharedLocale
): string {
  const active = locale ?? currentLocale
  const primary = active === 'en-US' ? lookup(enUS, key) : lookup(zhCN, key)
  const resolved = primary ?? lookup(zhCN, key) ?? key
  return interpolate(resolved, params)
}
